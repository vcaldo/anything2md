  echo $'      ;;'
  echo $''
  echo $'    \'batch\'*\'-f\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "markdown json html chunks")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'convert\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--api-key --debug --force-ocr --format --help --keep-originals --llm-service --move-originals --no-images --output-dir --pages --paginate --use-llm --vram -d -f -h -l -o -p")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'config\'*)'
