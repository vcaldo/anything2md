  echo $'    \'c\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--api-key --debug --force-ocr --format --help --keep-originals --llm-service --move-originals --no-images --output-dir --pages --paginate --use-llm --vram -d -f -h -l -o -p")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--help --version -h -v b batch c config convert")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'  esac'
  echo $'} &&'
  echo $'  complete -F _anything2md_completions anything2md'
  echo $''
  echo $'# ex: filetype=sh'
}