  echo $'# completely (https://github.com/bashly-framework/completely)'
  echo $'# Modifying it manually is not recommended'
  echo $''
  echo $'_anything2md_completions_filter() {'
  echo $'  local words="$1"'
  echo $'  local cur=${COMP_WORDS[COMP_CWORD]}'
  echo $'  local result=()'
  echo $''
  echo $'  # words the user already typed (excluding the command itself)'
  echo $'  local used=()'
  echo $'  if ((COMP_CWORD > 1)); then'
  echo $'    used=("${COMP_WORDS[@]:1:$((COMP_CWORD - 1))}")'
  echo $'  fi'
  echo $''
  echo $'  if [[ "${cur:0:1}" == "-" ]]; then'
  echo $'    # Completing an option: offer everything (including options)'
  echo $'    echo "$words"'
  echo $''
  echo $'  else'
  echo $'    # Completing a non-option: offer only non-options,'
  echo $'    # and don\'t re-offer ones already used earlier in the line.'
  echo $'    for word in $words; do'
  echo $'      [[ "${word:0:1}" == "-" ]] && continue'
  echo $''
  echo $'      local seen=0'
  echo $'      for u in "${used[@]}"; do'
  echo $'        if [[ "$u" == "$word" ]]; then'
  echo $'          seen=1'
  echo $'          break'
  echo $'        fi'
  echo $'      done'
  echo $'      ((!seen)) && result+=("$word")'
  echo $'    done'
  echo $''
  echo $'    echo "${result[*]}"'
  echo $'  fi'
  echo $'}'
  echo $''
  echo $'_anything2md_completions() {'
  echo $'  local cur=${COMP_WORDS[COMP_CWORD]}'
  echo $'  local compwords=()'
  echo $'  if ((COMP_CWORD > 0)); then'
  echo $'    compwords=("${COMP_WORDS[@]:1:$((COMP_CWORD - 1))}")'
  echo $'  fi'
  echo $'  local compline="${compwords[*]}"'
  echo $''
  echo $'  COMPREPLY=()'
  echo $''
  echo $'  case "$compline" in'
  echo $'    \'convert\'*\'--llm-service\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "gemini ollama claude openai")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'batch\'*\'--llm-service\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "gemini ollama claude openai")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'convert\'*\'--format\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "markdown json html chunks")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'c\'*\'--llm-service\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "gemini ollama claude openai")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'b\'*\'--llm-service\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "gemini ollama claude openai")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'batch\'*\'--format\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "markdown json html chunks")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'config status\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'config build\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--force --help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'config check\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'config pull\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--help --tag -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'config env\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--export --help --show-secrets -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'config gpu\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'b\'*\'--format\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "markdown json html chunks")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    \'c\'*\'--format\')'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "markdown json html chunks")" -- "$cur")'
  echo $'      ;;'
  echo $''
