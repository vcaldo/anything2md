  echo $'      ;;'
  echo $''
  echo $'    \'b\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_anything2md_completions_filter "--api-key --debug --force-ocr --format --help --include-hidden --keep-originals --llm-service --move-originals --no-images --output-dir --pages --paginate --recursive --skip-hidden --skip-processed --use-llm --vram --workers -d -f -h -l -o -p -r -w")" -- "$cur")'
